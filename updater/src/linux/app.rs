//! BetterGameExperience (Linux): installs, updates, repairs or removes the BetterGameExperience
//! proxies in Civilization VI under Steam Play (Proton), from the GitHub releases.
//! Same structure as `windows/app.rs`, with the same release and install logic (`release`,
//! `install`, shared by both), but command-line only: no window, no administrator.
//!
//!   BetterGameExperience                              menu (in a terminal)
//!   BetterGameExperience status                       installation status
//!   BetterGameExperience install                      installs or updates
//!   BetterGameExperience uninstall                    removes the proxies
//!   BetterGameExperience launch-option                tells which launch option to set in Steam
//!   BetterGameExperience channel release|prerelease   chooses the channel
//!   BetterGameExperience lang <code>                  chooses the language
//!   --game-dir <folder>                               game outside the Steam libraries
//!   --yes                                             no confirmation
//!   BetterGameExperience --after-game [<folder>]      (launched by the game, no terminal) waits for
//!                                                     the game to close and updates; asks no
//!                                                     questions, result in update.log and a desktop
//!                                                     notification (an error dialog on failure)
//!
//! The Steam launch option (`localconfig.vdf`) is never modified here: `launch-option` gives the
//! player the steps.

use std::fs;
use std::io::Write;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use crate::{game, install, lang, launch, release, sys, ui};
use install::{Action, State};
use lang::{f, t};
use crate::textes as tx;
use ui::Icon;

/// To enter in Civilization VI's launch options: without `winmm=n,b`, Wine loads its own `winmm` and
/// ignores BetterGameExperience's, next to the exe.
const LAUNCH_OPTION: &str = "WINEDLLOVERRIDES=\"winmm=n,b\" %command%";
/// The override alone, the part of `LAUNCH_OPTION` before `%command%`.
const OVERRIDE: &str = "WINEDLLOVERRIDES=\"winmm=n,b\"";

/// Script launched by the game (the startup proxy can only launch a script: Wine runs a static
/// binary as a Wine module). It gives the installer the environment of an ordinary process, without
/// what Steam adds to it (`LD_PRELOAD`…), and detaches it from the game.
const LAUNCHER: &str = "#!/bin/sh
# Generated by BetterGameExperience: do not edit by hand.
dir=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd) || exit 1
unset LD_PRELOAD
if [ -n \"${SYSTEM_LD_LIBRARY_PATH+x}\" ]; then
    LD_LIBRARY_PATH=$SYSTEM_LD_LIBRARY_PATH
    export LD_LIBRARY_PATH
else
    unset LD_LIBRARY_PATH
fi
if command -v setsid >/dev/null 2>&1; then
    exec setsid \"$dir/BetterGameExperience\" \"$@\" </dev/null >/dev/null 2>&1
fi
exec \"$dir/BetterGameExperience\" \"$@\" </dev/null >/dev/null 2>&1
";

pub fn main() {
    lang::init();
    let mut args: Vec<String> = std::env::args().skip(1).collect();
    let yes = take_flag(&mut args, "--yes");
    let game_dir = match take_value(&mut args, "--game-dir") {
        Ok(dir) => dir.map(PathBuf::from),
        Err(()) => return usage(),
    };
    let code = match args.first().map(String::as_str) {
        Some("--after-game") => after_game(args.get(1).map(PathBuf::from)),
        Some("status") => run(status(game_dir)),
        Some("install") => run(install_command(game_dir)),
        Some("uninstall") => run(uninstall_command(game_dir, yes)),
        Some("launch-option") => {
            println!("{}", launch_option_steps());
            0
        }
        Some("channel") => match args.get(1).map(String::as_str) {
            Some(c @ ("release" | "prerelease")) => {
                release::set_prerelease(c == "prerelease");
                println!("{c}");
                0
            }
            _ => return usage(),
        },
        Some("lang") => match args.get(1).and_then(|c| lang::LANGUAGES.iter().position(|l| l.code == c)) {
            Some(index) => {
                lang::set(index);
                println!("{}", lang::LANGUAGES[index].label);
                0
            }
            None => {
                let codes: Vec<&str> = lang::LANGUAGES.iter().map(|l| l.code).collect();
                eprintln!("{}", codes.join(" "));
                std::process::exit(2);
            }
        },
        None if ui::interactive() => run(interactive(game_dir)),
        _ => return usage(),
    };
    std::process::exit(code);
}

/// No terminal and no known command: says so on stderr (exit code 2).
fn usage() {
    eprintln!("{}", t(tx::LINUX_RUN_FROM_A_TERMINAL));
    std::process::exit(2);
}

fn take_flag(args: &mut Vec<String>, flag: &str) -> bool {
    let found = args.iter().position(|a| a == flag);
    if let Some(i) = found {
        args.remove(i);
    }
    found.is_some()
}

/// Value of `flag <value>`, removed from the arguments; `Err` if the value is missing.
fn take_value(args: &mut Vec<String>, flag: &str) -> Result<Option<String>, ()> {
    let Some(i) = args.iter().position(|a| a == flag) else { return Ok(None) };
    if i + 1 >= args.len() {
        return Err(());
    }
    args.remove(i);
    Ok(Some(args.remove(i)))
}

fn run(result: Result<(), String>) -> i32 {
    match result {
        Ok(()) => 0,
        Err(e) => failed(&e),
    }
}

fn failed(e: &str) -> i32 {
    ui::message(Icon::Error, t(tx::THE_OPERATION_FAILED), e);
    1
}

fn find_game(dir: Option<PathBuf>) -> Result<PathBuf, String> {
    match dir {
        Some(dir) => game::from_command(&dir).ok_or_else(|| f(tx::X_IS_NOT_THE_CIVILIZATION_VI, &[&dir.display()])),
        None => game::find().map_err(|not_found| f(tx::LINUX_GAME_NOT_FOUND_X, &[&not_found.list()])),
    }
}

/// Steps for the player to follow in Steam: the installer never writes the launch option.
fn launch_option_steps() -> String {
    f(tx::LINUX_LAUNCH_OPTION_STEPS_X, &[&LAUNCH_OPTION])
}

fn status(game: Option<PathBuf>) -> Result<(), String> {
    let game = find_game(game)?;
    let manifest = release::fetch_manifest(&release::work_dir());
    show(&describe(&game, &manifest));
    Ok(())
}

fn install_command(game: Option<PathBuf>) -> Result<(), String> {
    copy_self();
    let game = find_game(game)?;
    let work = release::work_dir();
    let m = release::fetch_manifest(&work)?;
    if install::status(&game, Some(&m)).iter().all(|(_, s)| *s == State::UpToDate) {
        show(&describe(&game, &Ok(m)));
        return Ok(());
    }
    ensure_closed()?;
    install_release(&m, &game, &work)?;
    installed(&m.version);
    Ok(())
}

fn uninstall_command(game: Option<PathBuf>, yes: bool) -> Result<(), String> {
    let game = find_game(game)?;
    if !yes && ui::interactive() {
        let options = [t(tx::UNINSTALL_RESTORES_THE_GAME_S_ORIGINAL), t(tx::CLOSE)];
        if ui::choose(t(tx::LINUX_CHOOSE_A_NUMBER), &options) != Some(0) {
            return Ok(());
        }
    }
    ensure_closed()?;
    uninstall(&game)
}

fn ensure_closed() -> Result<(), String> {
    if game::running() {
        return Err(t(tx::CLOSE_CIVILIZATION_VI_THEN_RUN_THE).into());
    }
    Ok(())
}

fn uninstall(game: &Path) -> Result<(), String> {
    let work = release::work_dir();
    ui::progress(t(tx::UNINSTALLING_BETTERGAMEDLLS), || install::run(Action::Uninstall, game, &work))?;
    release::remember_installed(None);
    remove_own_files(release::data_dir().as_deref(), &work);
    ui::message(Icon::Info, t(tx::BETTERGAMEDLLS_IS_UNINSTALLED), t(tx::THE_GAME_HAS_ITS_ORIGINAL_FILES));
    Ok(())
}

fn interactive(game: Option<PathBuf>) -> Result<(), String> {
    // On startup, not only after an install: a player who is already up to date and runs a newer
    // installer also updates the one the in-game notification launches.
    copy_self();
    let game = find_game(game)?;
    let work = release::work_dir();
    let mut manifest = release::fetch_manifest(&work);
    // Redone on every channel change.
    loop {
        let view = describe(&game, &manifest);
        show(&view);
        enum Entry {
            Install,
            Uninstall,
            Toggle,
            LaunchOption,
        }
        let mut entries = Vec::new();
        if !view.install_text.is_empty() {
            entries.push((Entry::Install, view.install_text.clone()));
        }
        if view.ours > 0 || view.old {
            entries.push((Entry::Uninstall, t(tx::UNINSTALL_RESTORES_THE_GAME_S_ORIGINAL).to_string()));
        }
        let mark = if view.prerelease { "x" } else { " " };
        entries.push((Entry::Toggle, format!("[{mark}] {}", t(tx::PRE_RELEASE_INSTALL_TEST_VERSIONS))));
        entries.push((Entry::LaunchOption, t(tx::LINUX_SHOW_THE_LAUNCH_OPTION).to_string()));
        let labels: Vec<&str> = entries.iter().map(|(_, l)| l.as_str()).chain([t(tx::CLOSE)]).collect();
        let Some(choice) = ui::choose(t(tx::LINUX_CHOOSE_A_NUMBER), &labels) else { return Ok(()) };
        match entries.get(choice).map(|(e, _)| e) {
            Some(Entry::Install) => {
                ensure_closed()?;
                let m = manifest?;
                install_release(&m, &game, &work)?;
                installed(&m.version);
                return Ok(());
            }
            Some(Entry::Uninstall) => {
                ensure_closed()?;
                return uninstall(&game);
            }
            Some(Entry::Toggle) => {
                release::set_prerelease(!release::prerelease());
                let mut fetched = Err(String::new());
                let _ = ui::progress(t(tx::LOOKING_FOR_THE_LATEST_VERSION), || {
                    fetched = release::fetch_manifest(&work);
                    Ok(())
                });
                manifest = fetched;
            }
            Some(Entry::LaunchOption) => {
                println!("{}", launch_option_steps());
                return Ok(());
            }
            None => return Ok(()),
        }
    }
}

/// What the main Windows window (`ask_action`) shows: here, as text.
struct View {
    icon: Icon,
    instruction: String,
    content: String,
    details: Vec<String>,
    /// Text of the install action; empty if there is nothing to install.
    install_text: String,
    /// Proxies in place, and an old installation to replace.
    ours: usize,
    old: bool,
    prerelease: bool,
    /// Proxies in place, but no Steam account has the launch option: they do not load.
    launch_option_missing: bool,
}

fn describe(game: &Path, manifest: &Result<release::Manifest, String>) -> View {
    let states = install::status(game, manifest.as_ref().ok());
    let ours = states.iter().filter(|(_, s)| matches!(s, State::Installed | State::UpToDate)).count();
    let old = states.iter().any(|(_, s)| *s == State::Old);
    let up_to_date = states.iter().all(|(_, s)| *s == State::UpToDate);
    let prerelease = release::prerelease();
    // Installed version newer than the channel's: a pre-release, which the release channel
    // replaces with the latest release (downgrade).
    let installed = release::installed_version();
    let downgrade = match (manifest, &installed) {
        (Ok(m), Some(v)) if ours > 0 && !up_to_date && release::is_newer(v, &m.version) => Some(v.clone()),
        _ => None,
    };

    let mut content = f(tx::GAME_X, &[&game.display()]);
    if prerelease {
        content += t(tx::CHANNEL_PRE_RELEASE_TEST_VERSIONS_AHEAD);
    }
    let (icon, instruction, install_text) = match manifest {
        Err(e) => {
            content += &f(tx::COULD_NOT_READ_THE_LATEST_VERSION, &[e]);
            (Icon::Warning, t(tx::LATEST_VERSION_UNKNOWN).to_string(), String::new())
        }
        Ok(m) if up_to_date => (Icon::Info, f(tx::BETTERGAMEDLLS_X_IS_INSTALLED_AND_UP, &[&m.version]), String::new()),
        Ok(m) if ours == 0 && !old => (
            Icon::Info,
            t(tx::BETTERGAMEDLLS_IS_NOT_INSTALLED).to_string(),
            f(tx::INSTALL_DOWNLOADS_AND_INSTALLS_VERSION_X, &[&m.version]),
        ),
        Ok(m) if old => (
            Icon::Info,
            f(tx::BETTERGAMEDLLS_VERSION_X_IS_AVAILABLE, &[&m.version]),
            f(tx::UPDATE_INSTALLS_VERSION_X_WHICH_NO, &[&m.version]),
        ),
        // Only some of them: a file was removed by hand.
        Ok(m) if ours < install::TARGETS.len() => (
            Icon::Warning,
            t(tx::BETTERGAMEDLLS_NEEDS_TO_BE_REPAIRED).to_string(),
            f(tx::REPAIR_REINSTALLS_VERSION_X, &[&m.version]),
        ),
        Ok(m) => match &downgrade {
            Some(v) => (
                Icon::Info,
                f(tx::BETTERGAMEDLLS_VERSION_X_IS_INSTALLED, &[v]),
                f(tx::GO_BACK_TO_VERSION_X_REPLACES, &[&m.version]),
            ),
            None => (
                Icon::Info,
                f(tx::BETTERGAMEDLLS_VERSION_X_IS_AVAILABLE, &[&m.version]),
                f(tx::UPDATE_INSTALLS_VERSION_X, &[&m.version]),
            ),
        },
    };
    let mut details: Vec<String> = states
        .iter()
        .map(|(name, state)| {
            let text = match state {
                State::Absent => t(tx::NOT_INSTALLED),
                State::Foreign => t(tx::FILE_FROM_ANOTHER_PROGRAM),
                State::Old => t(tx::OLD_PROXY_IN_PLACE_OF_THE),
                State::Installed => t(tx::PROXY_INSTALLED_OTHER_VERSION),
                State::UpToDate => t(tx::PROXY_UP_TO_DATE),
            };
            format!("{name} : {text}")
        })
        .collect();
    if let (Some(v), true) = (&installed, ours > 0) {
        details.push(f(tx::VERSION_INSTALLED_BY_THE_INSTALLER_X, &[v]));
    }
    // Only once installed: before that, the end of the install gives the steps anyway.
    let launch_option_missing = ours > 0 && launch::check() == launch::Check::Missing;
    View { icon, instruction, content, details, install_text, ours, old, prerelease, launch_option_missing }
}

fn show(view: &View) {
    println!();
    ui::message(view.icon, &view.instruction, &view.content);
    for line in &view.details {
        println!("  {line}");
    }
    println!();
    if view.launch_option_missing {
        ui::message(Icon::Warning, &f(tx::LINUX_LAUNCH_OPTION_MISSING_X, &[&OVERRIDE]), &launch_option_steps());
        println!();
    }
}

fn install_release(m: &release::Manifest, game: &Path, work: &Path) -> Result<(), String> {
    ui::progress(&f(tx::INSTALLING_BETTERGAMEDLLS_X, &[&m.version]), || {
        release::fetch_files(m, work)?;
        install::run(Action::Install, game, work)
    })?;
    release::remember_installed(Some(&m.version));
    copy_self();
    Ok(())
}

/// End of install: says everything is in place, and what is left to set in Steam.
fn installed(version: &str) {
    ui::message(Icon::Info, &f(tx::BETTERGAMEDLLS_X_IS_INSTALLED, &[&version]), &launch_option_steps());
}

/// Writes `data` to `path` through a temporary file next to it, then a rename: a running installer
/// or script is never half-replaced.
fn plant(path: &Path, data: &[u8], mode: u32) -> std::io::Result<()> {
    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("fichier");
    let temporary = path.with_file_name(format!(".{name}.new-{}", std::process::id()));
    let result = fs::write(&temporary, data)
        .and_then(|_| fs::set_permissions(&temporary, fs::Permissions::from_mode(mode)))
        .and_then(|_| fs::rename(&temporary, path));
    if result.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    result
}

/// Copies the installer and its launch script to the data directory, where the startup proxy looks
/// for them (`bge-launch.sh`): the copy follows the last installer run.
fn copy_self() {
    let Some(dir) = release::data_dir() else { return };
    if fs::create_dir_all(&dir).is_err() {
        return;
    }
    let stable = dir.join("BetterGameExperience");
    if let Ok(me) = std::env::current_exe() {
        if fs::canonicalize(&me).ok() != fs::canonicalize(&stable).ok() {
            if let Ok(data) = fs::read(&me) {
                let _ = plant(&stable, &data, 0o755);
            }
        }
    }
    let _ = plant(&dir.join("bge-launch.sh"), LAUNCHER.as_bytes(), 0o755);
}

/// Files this installer creates in its data directory: the installer copy and launch script
/// (`copy_self`), the language, channel and installed-version choices (`lang`, `release`), and
/// `update.log`.
const DATA_FILES: [&str; 6] = ["BetterGameExperience", "bge-launch.sh", "langue.txt", "canal.txt", "installe.txt", "update.log"];

/// After an uninstall, removes everything the installer left outside the game: the download cache
/// (`work`) entirely, and in the data directory only the installer's own files. The data directory
/// itself is removed only if nothing else is left in it. Deleting the running binary is fine on Linux.
fn remove_own_files(data: Option<&Path>, work: &Path) {
    let _ = fs::remove_dir_all(work);
    let Some(data) = data else { return };
    for name in DATA_FILES {
        let _ = fs::remove_file(data.join(name));
    }
    // Fails, and keeps the directory, if it still holds files that are not ours.
    let _ = fs::remove_dir(data);
}

/// One line of `update.log`: the installer launched by the game has no terminal.
fn log(line: &str) {
    let Some(dir) = release::data_dir() else { return };
    let _ = fs::create_dir_all(&dir);
    let Ok(mut file) = fs::OpenOptions::new().create(true).append(true).open(dir.join("update.log")) else { return };
    let secs = SystemTime::now().duration_since(UNIX_EPOCH).map_or(0, |d| d.as_secs());
    let _ = writeln!(file, "{secs} {line}");
}

/// Launched by the in-game notification, as the game closes: waits for it to exit (one minute at
/// most), updates, and records the result in `update.log`. Success is a desktop notification; a
/// failure is an error dialog, or a notification saying so if no dialog tool is available.
///
/// The game is not relaunched: this process is started by the game, so it stays under Steam's
/// `reaper`, and Steam counts the game as running until it exits. A `steam://rungameid` sent from
/// here is ignored. The player starts the game again from Steam (README.md, Linux).
fn after_game(dir: Option<PathBuf>) -> i32 {
    for _ in 0..120 {
        if !game::running() {
            break;
        }
        std::thread::sleep(Duration::from_millis(500));
    }
    let result = (|| {
        if game::running() {
            return Err(t(tx::CIVILIZATION_VI_DID_NOT_CLOSE_CLOSE).to_string());
        }
        // The folder received is only a hint: checked again, otherwise the game is searched for.
        let game = match dir.and_then(|d| game::from_command(&d)) {
            Some(game) => game,
            None => find_game(None)?,
        };
        let work = release::work_dir();
        let m = release::fetch_manifest(&work)?;
        install_release(&m, &game, &work)?;
        Ok::<_, String>(m.version)
    })();
    match result {
        Ok(version) => {
            let message = f(tx::BETTERGAMEDLLS_X_IS_INSTALLED, &[&version]);
            log(&message);
            sys::notify("BetterGameExperience", &message);
            0
        }
        Err(e) => {
            log(&format!("{}: {e}", t(tx::THE_OPERATION_FAILED)));
            // The previous version stays in place: the game still starts.
            sys::error("BetterGameExperience", &format!("{}\n\n{e}", t(tx::THE_OPERATION_FAILED)));
            1
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn arguments() {
        let mut args: Vec<String> = ["--game-dir", "/g", "status", "--yes"].map(String::from).into();
        assert!(take_flag(&mut args, "--yes"));
        assert!(!take_flag(&mut args, "--other"));
        assert_eq!(take_value(&mut args, "--game-dir"), Ok(Some("/g".to_string())));
        assert_eq!(args, ["status"]);
        let mut args: Vec<String> = ["--game-dir"].map(String::from).into();
        assert_eq!(take_value(&mut args, "--game-dir"), Err(()));
    }

    #[test]
    fn script_de_lancement() {
        // Arguments are passed through as-is, without eval.
        assert!(LAUNCHER.contains("\"$@\""));
        assert!(!LAUNCHER.contains("eval"));
        assert!(LAUNCHER.starts_with("#!/bin/sh\n"));
    }

    #[test]
    fn uninstall_removes_own_files_only() {
        let root = std::env::temp_dir().join(format!("bgd_remove_own_{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        let (data, work) = (root.join("data"), root.join("cache"));
        fs::create_dir_all(work.join("sub")).unwrap();
        fs::write(work.join("manifest.json"), b"{}").unwrap();
        fs::create_dir_all(&data).unwrap();
        for name in DATA_FILES {
            fs::write(data.join(name), b"x").unwrap();
        }

        // A file that is not ours keeps the data directory.
        fs::write(data.join("notes.txt"), b"x").unwrap();
        remove_own_files(Some(&data), &work);
        assert!(!work.exists());
        assert!(DATA_FILES.iter().all(|n| !data.join(n).exists()));
        assert!(data.join("notes.txt").exists());

        // Only our files: the directory goes too.
        fs::remove_file(data.join("notes.txt")).unwrap();
        fs::write(data.join("canal.txt"), b"x").unwrap();
        remove_own_files(Some(&data), &work);
        assert!(!data.exists());
        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn option_de_lancement() {
        assert_eq!(LAUNCH_OPTION, "WINEDLLOVERRIDES=\"winmm=n,b\" %command%");
        assert!(launch_option_steps().contains(LAUNCH_OPTION));
        assert_eq!(LAUNCH_OPTION, format!("{OVERRIDE} %command%"));
        // The option given to the player is the one the check recognises.
        assert!(launch::has_override(LAUNCH_OPTION));
    }
}
